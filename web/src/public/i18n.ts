export function labelName(label: Label, locale: Locale) {
  const key = label.preset?.toLowerCase().replaceAll(" ", "_");
  return key && presets[key]
    ? presets[key][locale === "pt" ? 1 : 0]
    : label.name;
}
export function dateString(value: string | undefined, locale: Locale) {
  if (!value || !Number.isFinite(Date.parse(value))) return "";
  return new Intl.DateTimeFormat(locale === "pt" ? "pt-BR" : "en", {
    month: "short",
    day: "numeric",
    year: "numeric",
  }).format(new Date(value));
}
