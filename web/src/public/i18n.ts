export type Translate = (key: keyof typeof english) => string;
export function translator(locale: Locale): Translate {
  return (key) => (locale === "pt" ? portuguese : english)[key];
}
export function getLocale(server?: string): Locale {
  const remembered = document.cookie
    .split("; ")
    .find((item) => item.startsWith("pb_lang="))
    ?.split("=")[1];
  return (remembered || server || navigator.language)
    .toLowerCase()
    .startsWith("pt")
    ? "pt"
    : "en";
}
